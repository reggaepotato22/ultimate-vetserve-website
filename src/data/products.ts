export const getCategoryConfig = (category: string) => {
  const configs: Record<string, { color: string; bg: string; bar: string }> = {
    "Injectables":            { color: "text-primary",    bg: "bg-primary/10",  bar: "bg-primary" },
    "Boluses & De-wormers":   { color: "text-emerald-600",bg: "bg-emerald-50",  bar: "bg-emerald-500" },
    "Water Solubles":         { color: "text-teal-600",   bg: "bg-teal-50",     bar: "bg-teal-500" },
    "Vaccines":               { color: "text-green-700",  bg: "bg-green-50",    bar: "bg-green-600" },
    "Disinfectants & Salves": { color: "text-lime-700",   bg: "bg-lime-50",     bar: "bg-lime-600" },
  };
  return configs[category] ?? { color: "text-primary", bg: "bg-primary/10", bar: "bg-primary" };
};

